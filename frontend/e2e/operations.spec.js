import { test, expect } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'
import { randomUUID } from 'node:crypto'
import { Workspace } from './workspace.js'

test('superadmin creates an enterprise and assigns a real administrative account', async ({ page }) => {
  const w = new Workspace(page)
  await w.login('root')
  await expect(page.getByRole('heading', { name: 'Global operations', exact: true })).toBeVisible()
  await w.nav('Companies')
  await page.getByRole('button', { name: 'Create company', exact: true }).click()
  const company = `E2E enterprise ${randomUUID().slice(0, 8)}`
  await page.getByLabel('Name', { exact: true }).fill(company)
  await page.getByRole('button', { name: 'Save changes', exact: true }).click()
  await expect(page.getByRole('cell', { name: company, exact: true })).toBeVisible()
  await w.nav('Branches')
  await page.getByRole('button', { name: 'Create branch', exact: true }).click()
  await page.getByRole('dialog').getByLabel('Company', { exact: true }).selectOption({ label: company })
  const branch = `HQ ${randomUUID().slice(0, 8)}`
  await page.getByLabel('Name', { exact: true }).fill(branch)
  await page.getByRole('button', { name: 'Save changes', exact: true }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await w.nav('Users')
  await page.getByRole('button', { name: 'Create user', exact: true }).click()
  const email = `f6-${randomUUID()}@example.test`
  await page.getByLabel('Email address').fill(email)
  await page.getByLabel('Password', { exact: true }).fill(`F6!${randomUUID()}`)
  await page.getByRole('dialog').getByLabel('Role', { exact: true }).selectOption('COMPANY_ADMIN')
  await page.getByLabel('Company', { exact: true }).selectOption({ label: company })
  await page.getByLabel('Assigned branch').selectOption({ label: branch })
  const saved = page.waitForResponse(r => r.url().endsWith('/users/') && r.request().method() === 'POST')
  await page.getByRole('button', { name: 'Save changes', exact: true }).click()
  const created = await saved
  expect(created.status()).toBe(201)
  expect((await created.json()).role).toBe('COMPANY_ADMIN')
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await page.getByRole('button', { name: `Edit ${email}`, exact: true }).click()
  await expect(page.getByRole('dialog').getByLabel('Password', { exact: true })).toHaveCount(0)
  await page.getByLabel('Account status', { exact: true }).selectOption('false')
  await page.getByRole('button', { name: 'Save changes', exact: true }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await page.getByRole('searchbox').fill(email)
  await expect(page.getByRole('row').filter({ hasText: email })).toContainText('Inactive')
  await w.nav('Companies')
  await page.getByRole('searchbox').fill(company)
  await page.getByRole('button', { name: `Edit ${company}`, exact: true }).click()
  await page.getByRole('dialog').getByLabel('Status', { exact: true }).selectOption('INACTIVE')
  await page.getByRole('button', { name: 'Save changes', exact: true }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await page.getByRole('button', { name: `Delete ${company}`, exact: true }).click()
  await page.getByRole('button', { name: 'Delete permanently', exact: true }).click()
  await expect(page.getByRole('alert')).toBeVisible()
  await page.getByRole('button', { name: 'Cancel', exact: true }).click()
  await page.getByRole('button', { name: `Edit ${company}`, exact: true }).click()
  await page.getByRole('dialog').getByLabel('Status', { exact: true }).selectOption('ACTIVE')
  await page.getByRole('button', { name: 'Save changes', exact: true }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
})

test('company admin manages branch, category, product and operator in its scope', async ({ page }) => {
  const w = new Workspace(page)
  await w.login('admin')
  await expect(page.getByRole('heading', { name: 'Company operations', exact: true })).toBeVisible()
  const suffix = randomUUID().slice(0, 8)
  await w.nav('Branches')
  await page.getByRole('button', { name: 'Create branch', exact: true }).click()
  await page.getByLabel('Name', { exact: true }).fill(`Branch ${suffix}`)
  await page.getByLabel('Address', { exact: true }).fill('Test warehouse')
  await page.getByRole('button', { name: 'Save changes', exact: true }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await w.nav('Categories')
  await page.getByRole('button', { name: 'Create category', exact: true }).click()
  await page.getByLabel('Category name').fill(`Category ${suffix}`)
  await page.getByRole('button', { name: 'Save category', exact: true }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await w.nav('Products')
  await page.getByRole('button', { name: 'Create product', exact: true }).click()
  await page.getByLabel('Name', { exact: true }).fill(`Product ${suffix}`)
  await page.getByLabel('SKU', { exact: true }).fill(`SKU-${suffix}`)
  await page.getByLabel('Category', { exact: true }).selectOption({ label: `Category ${suffix}` })
  await page.getByRole('button', { name: 'Save changes', exact: true }).click()
  await expect(page.getByRole('cell', { name: `Product ${suffix}`, exact: true })).toBeVisible()
  await page.getByRole('button', { name: `Edit Product ${suffix}`, exact: true }).click()
  await page.getByRole('dialog').getByLabel('Status', { exact: true }).selectOption('INACTIVE')
  await page.getByRole('button', { name: 'Save changes', exact: true }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await page.getByLabel('Status', { exact: true }).selectOption('INACTIVE')
  await page.getByRole('searchbox').fill(`Product ${suffix}`)
  await expect(page.getByRole('cell', { name: `Product ${suffix}`, exact: true })).toBeVisible()
  await page.getByRole('button', { name: `Delete Product ${suffix}`, exact: true }).click()
  await page.getByRole('button', { name: 'Delete permanently', exact: true }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await w.nav('Users')
  await page.getByRole('button', { name: 'Create user', exact: true }).click()
  await expect(page.getByRole('dialog').getByLabel('Role', { exact: true })).toHaveCount(0)
  const email = `operator-${randomUUID()}@example.test`
  await page.getByLabel('Email address').fill(email)
  await page.getByLabel('Password', { exact: true }).fill(`F6!${randomUUID()}`)
  await page.getByLabel('Assigned branch').selectOption({ label: `Branch ${suffix}` })
  await page.getByRole('button', { name: 'Save changes', exact: true }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await page.getByRole('button', { name: `Edit ${email}`, exact: true }).click()
  await page.getByLabel('Account status', { exact: true }).selectOption('false')
  await page.getByRole('button', { name: 'Save changes', exact: true }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await page.getByRole('searchbox').fill(email)
  await expect(page.getByRole('row').filter({ hasText: email })).toContainText('Inactive')
  for (const width of [320, 390, 768, 1440]) {
    await page.setViewportSize({ width, height: 1000 })
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
  }
  await page.setViewportSize({ width: 390, height: 1000 })
  const a11y = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze()
  expect(a11y.violations).toEqual([])
})

